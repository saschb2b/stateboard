/** Cookie mutations must originate from this deployment, including behind a proxy. */
export function isTrustedMutationOrigin(
  requestUrl: string,
  headers: Headers,
  configuredBaseUrl?: string,
): boolean {
  if (headers.get("sec-fetch-site") === "cross-site") return false;
  const origin = headers.get("origin");
  if (!origin || origin === "null") return false;
  try {
    const source = new URL(origin);
    const expected = new URL(configuredBaseUrl || requestUrl);
    return (
      (source.protocol === "https:" || source.protocol === "http:") &&
      source.origin === expected.origin &&
      source.pathname === "/" &&
      !source.search &&
      !source.hash &&
      !source.username &&
      !source.password
    );
  } catch {
    return false;
  }
}

export function parseExpectedRevision(value: unknown): number | null {
  return typeof value === "number" && Number.isSafeInteger(value) && value > 0
    ? value
    : null;
}

const EXISTING_RESOURCE_ACTIONS = new Set([
  "capability.update",
  "capability.archive",
  "component.update",
  "component.archive",
  "dependency.delete",
  "check.revise",
  "check.archive",
]);

/** Generated identities cannot be overwritten through a creation envelope. */
export function mutationIdError(type: string, id: unknown): string | null {
  if (type.endsWith(".create") && id !== undefined) {
    return "Creation IDs are generated by StateBoard; do not supply id";
  }
  if (EXISTING_RESOURCE_ACTIONS.has(type)) {
    if (typeof id !== "string" || !/^[A-Za-z0-9_-]{1,200}$/.test(id)) {
      return "A valid existing resource id is required for this action";
    }
  } else if (id !== undefined) {
    return "This action identifies its relationship through data; do not supply id";
  }
  return null;
}
